import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
const docs=new URL('./docs/',import.meta.url);
const bundles=[
 {file:'storefront-bundle.js',sources:['catalog.js','product-motion.js','product-content.js','cart.js','storefront.js','hero-slider.js'],pages:['index.html','products.html']},
 {file:'cart-bundle.js',sources:['catalog.js','cart.js','about.js','cart-page.js'],pages:['cart.html']},
 {file:'checkout-bundle.js',sources:['catalog.js','cart.js','customer-data.js','checkout-config.js','checkout.js'],pages:['checkout.html']}
];
for(const bundle of bundles){
 const parts=await Promise.all(bundle.sources.map(async name=>'/* '+name+' */\n'+await fs.readFile(new URL(name,docs),'utf8')));
 const contents='/* Generated by node build-storefront.mjs. Edit the source files, then rebuild. */\n'+parts.join('\n;\n'),version=createHash('sha256').update(contents).digest('hex').slice(0,12);
 await fs.writeFile(new URL(bundle.file,docs),contents);
 const names=[...bundle.sources,bundle.file].map(name=>name.replaceAll('.','\\.')).join('|');
 for(const name of bundle.pages){
  const file=new URL(name,docs);let html=await fs.readFile(file,'utf8');
  html=html.replace(new RegExp('<script (?:defer )?src="(?:'+names+')[^\\"]*"><\\/script>\\s*','g'),'');
  html=html.replace('</body>','<script defer src="'+bundle.file+'?v='+version+'"></script>\n</body>');
  await fs.writeFile(file,html);
 }
}
console.log('Storefront, cart and customer-details dependency bundles rebuilt.');
