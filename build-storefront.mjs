import fs from 'node:fs/promises';
const docs=new URL('./docs/',import.meta.url);
const sources=['catalog.js','product-motion.js','product-content.js','cart.js','storefront.js','hero-slider.js'];
const parts=await Promise.all(sources.map(async name=>'/* '+name+' */\n'+await fs.readFile(new URL(name,docs),'utf8')));
await fs.writeFile(new URL('storefront-bundle.js',docs),'/* Generated by node build-storefront.mjs. Edit the source files, then rebuild. */\n'+parts.join('\n;\n'));
for(const name of ['index.html','products.html']){
 const file=new URL(name,docs);let html=await fs.readFile(file,'utf8');
 html=html.replace(/<script defer src="(?:catalog|product-motion|product-content|cart|storefront|hero-slider)\.js[^\"]*"><\/script>\s*/g,'').replace(/<script defer src="storefront-bundle\.js[^\"]*"><\/script>\s*/g,'');
 html=html.replace('</body>','<script defer src="storefront-bundle.js?v=loading-bundle-20261120"></script>\n</body>');
 await fs.writeFile(file,html);
}
console.log('Storefront dependency bundle rebuilt.');
